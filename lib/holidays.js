export function isHoliday(dateString) {
  return GERMAN_HOLIDAYS.some(h => h.date === dateString);
}
 
export function isWeekend(date) {
  return date.getDay() === 0 || date.getDay() === 6;
}
 
export function countWorkingDays(startDateString, endDateString) {
  const start = new Date(startDateString);
  const end = new Date(endDateString);
  let count = 0;
 
  for (let d = new Date(start); d <= end; d.setDate(d.getDate() + 1)) {
    const dateStr = d.toISOString().split('T')[0];
    if (!isHoliday(dateStr) && !isWeekend(d)) {
      count++;
    }
  }
  return count;
}
 
// Liefert alle Feiertage eines Jahres (wird von page.jsx verwendet)
export function getHolidays(year) {
  return GERMAN_HOLIDAYS.filter(h => h.date.startsWith(String(year)));
}
 
